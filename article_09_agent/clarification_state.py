"""
ClarificationState — canonical, code-assembled store for clarifications
gathered mid-conversation (Article 9).

Design principle: a fact that already exists in pipeline state should be
read once from a single source of truth, never regenerated by an LLM.
This module is that single source of truth for clarifications. The
supervisor and specialists read from it; nothing downstream re-derives
it from raw text.

Known boundary (stated, not solved here): order_id, email, and phone are
still extracted independently by each specialist via regex in tools.py.
That path already works once the full customer_message reaches a
specialist intact (see the supervisor.py fix). This module exists for
facts regex cannot reliably capture — anything free-form that requires
judgment to classify, e.g. a stated resolution preference.
"""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel


# Fixed, finite set of clarification keys this domain recognises.
# This list is a closed contract: the classifier (clarification_classifier.py)
# may only return one of these values, or "no_match". It must never invent
# a new key — an unbounded keyspace is exactly what would break every
# downstream consumer that needs to read a known field.
KNOWN_CLARIFICATION_KEYS = [
    "resolution_preference",   # e.g. refund vs. replacement vs. store credit
    "refund_reason",           # why the customer believes a refund is owed
    "delivery_instructions",   # e.g. leave with neighbour, alternate address
    "contact_preference",      # preferred contact method or time
]

# Used by the classifier's structured output. Keeping this as a Literal
# means an out-of-set value is a validation error, not a possibility —
# the output space is closed by construction, not by convention.
ClarificationKey = Literal[
    "resolution_preference",
    "refund_reason",
    "delivery_instructions",
    "contact_preference",
    "no_match",
]


class ClarificationState:
    """
    Canonical store for clarifications gathered mid-conversation.

    facts               : current snapshot, one value per known key.
                          Specialists read this by default.
    facts_history       : append-only log of every write to `facts`,
                          each entry tagged with a timestamp. Not yet
                          read by any specialist in this build — kept
                          for consumers that need the correction trail
                          (e.g. Escalation, deferred to a later article).
    unstructured_notes  : append-only log of clarification text that did
                          not match any known key. Stored verbatim, never
                          dropped, never reclassified after the fact.
    """

    def __init__(self):
        self.facts: dict[str, str] = {}
        self.facts_history: list[dict] = []
        self.unstructured_notes: list[dict] = []

    def record_fact(self, key: str, value: str) -> None:
        """
        Write a fact to the current snapshot and append it to history in
        the same operation, so the two structures cannot drift apart.
        Overwrites any prior value for this key, by design — facts is a
        snapshot of what's currently true, not a log.
        """
        timestamp = datetime.now().isoformat()
        self.facts[key] = value
        self.facts_history.append({
            "key": key,
            "value": value,
            "timestamp": timestamp
        })

    def record_unstructured(self, text: str) -> None:
        """
        Store clarification text that matched no known key, verbatim.
        This is the overflow path — it must never be silently dropped.
        """
        self.unstructured_notes.append({
            "value": text,
            "timestamp": datetime.now().isoformat()
        })

    def facts_summary(self) -> str:
        """
        Code-assembled, read-only projection of current facts for
        inclusion in a specialist payload. Pure formatting — no LLM
        involvement, so nothing here can drop or reword a fact.
        """
        if not self.facts:
            return "None recorded"
        return "\n".join(f"  {k}: {v}" for k, v in self.facts.items())


class SpecialistPayload(BaseModel):
    """
    Contract every specialist payload must satisfy before dispatch.
    Validating here converts a silent omission into a loud, catchable
    failure at the supervisor boundary, instead of a specialist quietly
    receiving less than it should have — which is exactly how the
    Article 8 bug went unnoticed until the test traces were inspected.
    """
    customer_message: str
    prior_context: str